_SKILL_ROOT = Path(__file__).parent.parent


def _generate_base_project(
    tmp_path: Path,
    name: str = "tc",
    models: dict | None = None,
    owner_models: dict | None = None,
    with_otel: bool = False,
    with_prometheus: bool = False,
) -> Path:
    """Generate a FastAPI project via the orchestrator into *tmp_path*."""
    sys.path.insert(0, str(_SKILL_ROOT))
    from generators.orchestrator import generate_project  # noqa: PLC0415

    if models is None:
        models = {"Item": {"name": "str", "price": "int"}}
    if owner_models is None:
        owner_models = {"Item": "user"}

    project_dir = tmp_path / name
    result = generate_project(
        output_dir=str(project_dir),
        name=name,
        models=models,
        owner_models=owner_models,
        with_otel=with_otel,
        with_prometheus=with_prometheus,
    )
    assert result["total_files"] > 0, "orchestrator produced no files"
    return project_dir


def _install_requirements(project_dir: Path) -> None:
    """Create a venv inside *project_dir* and install requirements.txt."""
    venv_dir = project_dir / ".venv"
    subprocess.run(
        [sys.executable, "-m", "venv", str(venv_dir)],
        check=True,
        capture_output=True,
    )
    pip = venv_dir / "bin" / "pip"
    subprocess.run(
        [str(pip), "install", "-r", str(project_dir / "requirements.txt"), "-q"],
        check=True,
        capture_output=True,
        timeout=240,
    )


def _run_pytest_in_project(project_dir: Path) -> subprocess.CompletedProcess:
    """Run pytest inside the generated project's venv and return the result."""
    python = project_dir / ".venv" / "bin" / "python3"
    return subprocess.run(
        [
            str(python),
            "-m",
            "pytest",
            "tests/",
            "-v",
            "--tb=short",
            "--no-header",
        ],
        cwd=str(project_dir),
        env={
            **__import__("os").environ,
            "PYTHONPATH": str(project_dir),
        },
        capture_output=True,
        text=True,
        timeout=120,
    )


