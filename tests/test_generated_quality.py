class TestGeneratedTestsPass:
    """Blind Spot A — the test files written by generate_test_suite() must pass."""

    def test_generated_test_files_exist(self, tmp_path: Path) -> None:
        """Orchestrator must produce conftest.py + test_*.py files."""
        project_dir = _generate_base_project(tmp_path)
        test_files = sorted(project_dir.glob("tests/**/*.py"))
        test_names = [f.name for f in test_files]

        assert "conftest.py" in test_names, "Missing tests/conftest.py"
        assert any(n.startswith("test_") for n in test_names), (
            f"No test_*.py files found. Got: {test_names}"
        )

    def test_generated_test_files_have_no_syntax_errors(self, tmp_path: Path) -> None:
        """Every generated test file must be syntactically valid Python."""
        project_dir = _generate_base_project(tmp_path)
        for py_file in sorted(project_dir.glob("tests/**/*.py")):
            source = py_file.read_text()
            try:
                ast.parse(source)
            except SyntaxError as exc:
                pytest.fail(f"SyntaxError in {py_file.relative_to(project_dir)}: {exc}")

    def test_generated_tests_pass_with_sqlite(self, tmp_path: Path) -> None:
        """All 19 generated tests must pass using the SQLite test backend.

        This is the critical end-to-end check: generate → install deps → pytest.
        If ANY test fails for a reason OTHER than a missing external service
        (e.g. PostgreSQL), it is flagged as a real bug.
        """
        project_dir = _generate_base_project(tmp_path)
        _install_requirements(project_dir)

        proc = _run_pytest_in_project(project_dir)

        # Parse summary line, e.g. "19 passed, 3 warnings in 3.5s"
        passed = re.search(r"(\d+) passed", proc.stdout)
        failed = re.search(r"(\d+) failed", proc.stdout)
        errors = re.search(r"(\d+) error", proc.stdout)

        n_passed = int(passed.group(1)) if passed else 0
        n_failed = int(failed.group(1)) if failed else 0
        n_errors = int(errors.group(1)) if errors else 0

        assert proc.returncode == 0, (
            f"Generated tests FAILED (rc={proc.returncode})\n"
            f"--- stdout ---\n{proc.stdout[-3000:]}\n"
            f"--- stderr ---\n{proc.stderr[-1000:]}"
        )
        assert n_failed == 0, f"{n_failed} generated tests failed"
        assert n_errors == 0, f"{n_errors} generated tests errored"
        assert n_passed >= 19, f"Expected at least 19 tests to pass, got {n_passed}"

    def test_generated_test_count_matches_model_count(self, tmp_path: Path) -> None:
        """One test_<model>.py file must exist per domain model."""
        project_dir = _generate_base_project(
            tmp_path,
            models={"Item": {"name": "str"}, "Order": {"total": "Decimal"}},
            owner_models={"Item": "user", "Order": "user"},
        )
        route_tests = list(project_dir.glob("tests/api/routes/test_*.py"))
        test_names = {f.stem for f in route_tests}

        # Expect test_item, test_order, test_login, test_users
        assert "test_item" in test_names, f"Missing test_item. Got: {test_names}"
        assert "test_order" in test_names, f"Missing test_order. Got: {test_names}"
        assert "test_login" in test_names, f"Missing test_login. Got: {test_names}"
        assert "test_users" in test_names, f"Missing test_users. Got: {test_names}"

    def test_conftest_uses_sqlite_not_postgres(self, tmp_path: Path) -> None:
        """conftest.py must use SQLite (aiosqlite) so tests run without a DB server."""
        project_dir = _generate_base_project(tmp_path)
        conftest = (project_dir / "tests" / "conftest.py").read_text()

        assert "sqlite+aiosqlite" in conftest, (
            "conftest.py does not use SQLite — tests would require a live DB"
        )
        assert "asyncpg" not in conftest, (
            "conftest.py references asyncpg — tests would fail without PostgreSQL"
        )

    def test_conftest_disables_rate_limiting(self, tmp_path: Path) -> None:
        """conftest.py must disable rate limiting to avoid 429s during tests."""
        project_dir = _generate_base_project(tmp_path)
        conftest = (project_dir / "tests" / "conftest.py").read_text()

        assert "RATE_LIMITING_ENABLED" in conftest, (
            "conftest.py must set RATE_LIMITING_ENABLED=false before importing app"
        )


